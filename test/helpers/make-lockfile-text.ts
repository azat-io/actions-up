/**
 * Content of a workflow lockfile as a test describes it.
 */
interface LockfileDescription {
  /**
   * Commit each pin resolves to, as 40 hex digits, keyed by `owner/repo@ref`.
   */
  dependencies?: Record<string, string>

  /**
   * Pins each tracked workflow depends on, keyed by its repository path.
   */
  workflows?: Record<string, string[]>

  /**
   * Schema version. Defaults to `v0.0.3`.
   */
  version?: string
}

/**
 * Text of a workflow lockfile written the way gh-actions-lock writes it: a
 * header comment, single-quoted strings and four-space indentation.
 *
 * @param description - Workflows, dependencies and schema version.
 * @returns Content of `.github/workflows/actions.lock`.
 */
export function makeLockfileText(description: LockfileDescription): string {
  let { version = 'v0.0.3', dependencies = {}, workflows = {} } = description
  let lines = [
    '# This file is machine-generated by `gh actions-lock`.',
    '# Do not edit by hand; run `gh actions-lock` to update.',
    '# Docs: https://gh.io/actions-lockfile',
    `version: '${version}'`,
  ]

  if (Object.keys(workflows).length > 0) {
    lines.push('workflows:')
    for (let [workflow, pins] of Object.entries(workflows)) {
      lines.push(`    '${workflow}':${pins.length === 0 ? ' []' : ''}`)
      for (let pin of pins) {
        lines.push(`        - '${pin}'`)
      }
    }
  }

  if (Object.keys(dependencies).length > 0) {
    lines.push('dependencies:')
    for (let [pin, commit] of Object.entries(dependencies)) {
      lines.push(
        `    '${pin}':`,
        `        ref: '${pin.slice(pin.indexOf('@') + 1)}'`,
        `        commit: 'sha1-${commit}'`,
        '        owner_id: 44036562',
        '        repo_id: 197814629',
      )
    }
  }

  return `${lines.join('\n')}\n`
}
